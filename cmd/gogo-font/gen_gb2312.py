#!/usr/bin/env python3
"""Regenerates gb2312.go (the GB 2312-80 character table used by gogo-font).

The table comes from Python's "gb2312" codec, which is the only place the
character set is read from; the generated Go file is committed so that
building gogo-font needs nothing beyond the Go standard library.

    python3 cmd/gogo-font/gen_gb2312.py > cmd/gogo-font/gb2312.go
"""
import sys

chars = set()
for lead in range(0xA1, 0xF8):  # rows 1-87
    for trail in range(0xA1, 0xFF):
        try:
            chars.add(ord(bytes([lead, trail]).decode("gb2312")))
        except UnicodeDecodeError:
            pass
text = "".join(chr(c) for c in sorted(chars))
assert len(text) == 7445, len(text)  # 6763 hanzi + 682 symbols

print("// Code generated by gen_gb2312.py from Python's \"gb2312\" codec; DO NOT EDIT.")
print("//")
print("// gb2312Chars lists every character of GB 2312-80 (7445 code points: 6763")
print("// hanzi plus 682 symbols and letters) as UTF-8, in code point order. It is")
print("// committed so gogo-font needs only the Go standard library; regenerate with")
print("// `python3 cmd/gogo-font/gen_gb2312.py > cmd/gogo-font/gb2312.go`.")
print()
print("package main")
print()
print('const gb2312Chars = "" +')
lines = [text[i:i + 40] for i in range(0, len(text), 40)]
print(" +\n".join('\t"%s"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines))
