// Command floatcorpus writes runtime/vm/test/float_corpus.h: float values
// with formats and what Go's strconv.FormatFloat (and so Go's println, which
// is FormatFloat(v, 'g', -1, width)) gives for them. The C tests
// (runtime/vm/test/test_float.c) check gogo's float -> decimal conversion
// (runtime/vm/floats.c, runtime/floatlib/floatlib.c) against it. Run it with
// `make float-corpus` from the repository root; TestCorpusUpToDate fails
// when the file is stale (a different Go, or a change to the corpus).
package main

import (
	"fmt"
	"math"
	"math/rand"
	"os"
	"strconv"
	"strings"
)

const out = "runtime/vm/test/float_corpus.h"

func main() {
	if err := os.WriteFile(out, []byte(generate()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

type entry struct {
	bits uint64
	is32 bool
	fmt  byte
	prec int
}

// edges are values whose printing is easy to get wrong: zeros, infinities,
// NaN, subnormals, the extremes, the %e / %f switch points of %g, powers of
// two and ten, and halves that fixed precision must round to even.
var edges = []float64{
	0, math.Copysign(0, -1), math.Inf(1), math.Inf(-1), math.NaN(),
	math.SmallestNonzeroFloat64, 2 * math.SmallestNonzeroFloat64, 0x1p-1022, 0x1p-1022 - 0x1p-1074,
	math.MaxFloat64, -math.MaxFloat64, 1, -1, 0.1, 0.2, 0.3, 1.0 / 3, 2.0 / 3, 1.5, -1.5,
	1e21, 1e20, 999999, 1e6, 123456, 1234567, 1e-4, 1e-5, 0.0001234, 0.00001234,
	100, 1e23, 5e-324, 9007199254740992, 9007199254740993, 4503599627370496.5,
	0.5, 2.5, 0.125, 0.375, 1.005, 2.675, 1e15, 1e16, 1e17, 123456789012345678,
	math.Pi, math.E, math.Sqrt2, 3.4028234663852886e38, 1.401298464324817e-45, 1.1754943508222875e-38,
	0x1p52, 0x1p53, 0x1p-1, 0x1p63, 0x1p64, 1e308, 1e-308, 2.2250738585072014e-308,
}

var formats = []struct {
	fmt  byte
	prec int
}{{'g', -1}, {'e', -1}, {'f', -1}, {'g', 3}, {'e', 0}, {'e', 5}, {'f', 0}, {'f', 2}, {'f', 20}, {'g', 17}, {'G', 1}, {'E', 10}, {'b', -1}}

func corpus() []entry {
	var es []entry
	for _, v := range edges {
		for _, is32 := range []bool{false, true} {
			bits := math.Float64bits(v)
			if is32 {
				bits = uint64(math.Float32bits(float32(v)))
			}
			for _, f := range formats {
				es = append(es, entry{bits, is32, f.fmt, f.prec})
			}
		}
	}
	r := rand.New(rand.NewSource(1))
	fmts := []byte{'e', 'f', 'g'}
	for i := 0; i < 1500; i++ {
		is32 := i%3 == 0
		var bits uint64
		switch i % 4 {
		case 0, 1: // any bit pattern
			bits = r.Uint64()
		case 2: // a short decimal
			bits = math.Float64bits(float64(r.Int63n(1000000)) * math.Pow10(r.Intn(40)-20))
		default: // near the subnormals
			bits = r.Uint64() & 0x801FFFFFFFFFFFFF
		}
		if is32 {
			bits = uint64(math.Float32bits(float32(math.Float64frombits(bits))))
			if i%4 == 0 {
				bits = uint64(r.Uint32())
			}
		}
		f, prec := byte('g'), -1 // println's format: half of them
		if i%2 == 1 {
			f, prec = fmts[r.Intn(3)], r.Intn(25)
		}
		es = append(es, entry{bits, is32, f, prec})
	}
	return es
}

func generate() string {
	var b strings.Builder
	b.WriteString("/* Generated by tools/floatcorpus (make float-corpus); do not edit.\n" +
		" * Each entry: a float64 (is32 0) or float32 (is32 1) by its bits, a\n" +
		" * format and precision, and Go's strconv.FormatFloat for it. 'g' with\n" +
		" * precision -1 is also what Go's println prints. */\n")
	b.WriteString("static const struct FloatCase {\n    uint64_t bits;\n    uint8_t is32;\n    char fmt;\n    int16_t prec;\n    const char *want;\n} float_corpus[] = {\n")
	for _, e := range corpus() {
		v := math.Float64frombits(e.bits)
		size := 64
		if e.is32 {
			v = float64(math.Float32frombits(uint32(e.bits)))
			size = 32
		}
		is := 0
		if e.is32 {
			is = 1
		}
		fmt.Fprintf(&b, "    {0x%016xull, %d, '%c', %d, %q},\n", e.bits, is, e.fmt, e.prec, strconv.FormatFloat(v, e.fmt, e.prec, size))
	}
	b.WriteString("};\n")
	return b.String()
}
