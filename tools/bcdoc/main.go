// Command bcdoc generates docs/bytecode.md from runtime/vm/opcodes.h (and
// the image constants in runtime/vm/image.h). The structured comment format
// is described in the header of opcodes.h.
//
//	go run ./tools/bcdoc            # write docs/bytecode.md
//	go run ./tools/bcdoc -check     # exit 1 if docs/bytecode.md is stale
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

type op struct {
	name             string
	num              int
	operands, effect string
	desc             string
	ext              bool
	args, results    string // builtins
}

type def struct {
	name    string
	value   string
	comment string
}

var (
	opRe  = regexp.MustCompile(`^\s*OP_(\w+)\s*=\s*(\d+),?\s*(.*)$`)
	bRe   = regexp.MustCompile(`^\s*B_(\w+)\s*=\s*(\d+),?\s*(.*)$`)
	tagRe = regexp.MustCompile(`^/\*!\s*(.*?)\s*\*/`)
	defRe = regexp.MustCompile(`^#define\s+(TY_\w+|TYPE_[A-Z_0-9]+)\s+(\S+)\s*(?:/\*\s*(.*?)\s*\*/)?\s*$`)
	rsnRe = regexp.MustCompile(`^\s*R_(\w+)\s*=\s*(\d+),?\s*(?:/\*\s*(.*?)\s*\*/)?`)
	extRe = regexp.MustCompile(`case OP_(\w+):`)
)

func parse(src string) (ops, builtins []op, tys, types, reasons []def, err error) {
	section := ""
	ext := map[string]bool{}
	if body := regexp.MustCompile(`(?s)op_has_ext.*?return true;`).FindString(src); body != "" {
		for _, m := range extRe.FindAllStringSubmatch(body, -1) {
			ext[m[1]] = true
		}
	}
	for i, line := range strings.Split(src, "\n") {
		where := fmt.Sprintf("opcodes.h:%d", i+1)
		switch {
		case strings.HasPrefix(line, "enum Op {"):
			section = "op"
			continue
		case strings.HasPrefix(line, "enum Builtin {"):
			section = "b"
			continue
		case strings.HasPrefix(line, "enum Reason {"):
			section = "r"
			continue
		case strings.HasPrefix(line, "};"):
			section = ""
			continue
		}
		if m := defRe.FindStringSubmatch(line); m != nil {
			d := def{m[1], m[2], m[3]}
			if strings.HasPrefix(m[1], "TY_") {
				tys = append(tys, d)
			} else if _, e := strconv.Atoi(m[2]); e == nil && m[1] != "TYPE_RESERVED_COUNT" && m[1] != "TYPE_OWN_BASE" {
				types = append(types, d)
			}
			continue
		}
		switch section {
		case "op", "b":
			re := opRe
			if section == "b" {
				re = bRe
			}
			m := re.FindStringSubmatch(line)
			if m == nil {
				continue // blank or plain comment line
			}
			n, _ := strconv.Atoi(m[2])
			o := op{name: m[1], num: n}
			tag := tagRe.FindStringSubmatch(m[3])
			if tag == nil {
				err = fmt.Errorf("%s: %s has no structured /*! ... */ comment on its line", where, m[1])
				return
			}
			text := tag[1]
			if section == "op" {
				f := strings.Split(text, " | ")
				if len(f) < 3 {
					err = fmt.Errorf("%s: OP_%s: want OPERANDS | EFFECT | DESCRIPTION, got %q", where, m[1], text)
					return
				}
				o.operands, o.effect, o.desc = f[0], f[1], strings.Join(f[2:], " | ")
				o.ext = ext[m[1]]
				if o.ext != strings.Contains(o.operands, "ext") {
					err = fmt.Errorf("%s: OP_%s: op_has_ext says %v but OPERANDS %q disagree", where, m[1], o.ext, o.operands)
					return
				}
				ops = append(ops, o)
			} else {
				k := strings.LastIndex(text, " | ")
				if k < 0 {
					err = fmt.Errorf("%s: B_%s: want ARGS -> RESULTS | DESCRIPTION, got %q", where, m[1], text)
					return
				}
				sig, desc := text[:k], text[k+3:]
				j := strings.Index(sig, "->")
				if j < 0 {
					err = fmt.Errorf("%s: B_%s: signature %q has no ->", where, m[1], sig)
					return
				}
				o.args, o.results, o.desc = strings.TrimSpace(sig[:j]), strings.TrimSpace(sig[j+2:]), desc
				builtins = append(builtins, o)
			}
		case "r":
			if m := rsnRe.FindStringSubmatch(line); m != nil {
				reasons = append(reasons, def{m[1], m[2], m[3]})
			}
		}
	}
	for _, list := range [][]op{ops, builtins} {
		for i, o := range list {
			if o.num != i {
				err = fmt.Errorf("%s: number %d is not contiguous (expected %d)", o.name, o.num, i)
				return
			}
		}
	}
	if len(ops) == 0 || len(builtins) == 0 {
		err = fmt.Errorf("no opcodes or builtins parsed")
	}
	return
}

func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

func code(s string) string {
	if s == "" || s == "-" {
		return "-"
	}
	return "`" + cell(s) + "`"
}

func macro(src, name string) string {
	m := regexp.MustCompile(`#define\s+` + name + `\s+(\S+)`).FindStringSubmatch(src)
	if m == nil {
		return "?"
	}
	return strings.TrimSuffix(m[1], "u")
}

func generate(opcodesH, imageH string) (string, error) {
	ops, builtins, tys, types, reasons, err := parse(opcodesH)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# gogo bytecode reference\n\n")
	w("<!-- Generated by tools/bcdoc from runtime/vm/opcodes.h and runtime/vm/image.h. Do not edit:\n")
	w("     edit the structured comments in opcodes.h and run `make bytecode-doc`. -->\n\n")
	w("This is the per-opcode reference for the gogo VM, generated from the single source of truth,\n")
	w("`runtime/vm/opcodes.h` (the Go compiler parses the same file, `compiler/opcodes.go` mirrors it and\n")
	w("`TestOpcodesMatchC` keeps the two equal). The design behind it is in [design.md](design.md) §5.6\n")
	w("(bytecode, image layout, versioning) and §5.5 (value representation); `gogo dis file.ggb` prints a\n")
	w("program's bytecode. Image format %s.%s.\n\n", macro(imageH, "IMAGE_MAJOR"), macro(imageH, "IMAGE_MINOR"))
	w("## Contents\n\n- [Instruction encoding](#instruction-encoding)\n- [Opcodes](#opcodes) (%d)\n- [Builtins](#builtins) (%d)\n", len(ops), len(builtins))
	w("- [Type ids and reserved types](#type-ids-and-reserved-types)\n- [Exit reasons](#exit-reasons)\n- [Image file layout](#image-file-layout)\n\n")

	w("## Instruction encoding\n\n")
	w("An instruction is one little-endian 32-bit word: `op | a<<8 | b<<16 | c<<24` (opcode in the low\n")
	w("byte, then three 8-bit operands). Ops marked **+ext** are followed by one extra 32-bit word, `ext`,\n")
	w("which is not decoded as an instruction (a jump may land on it, so it is checked when used).\n")
	w("The VM is register-based: `ra`, `rb`, `rc` are the registers numbered by operands `a`, `b`, `c` in the\n")
	w("current frame; there is no operand stack, so \"effect\" is register notation. Function indexes, type\n")
	w("ids and jump targets (absolute code word indexes) are checked when used, and an out-of-range one is\n")
	w("`badcode` (the actor crashes with `R_BAD_CODE`).\n\n")

	w("## Opcodes\n\n")
	w("| # | Name | Operands | Ext | Effect | Description |\n|---|---|---|---|---|---|\n")
	for _, o := range ops {
		e := ""
		if o.ext {
			e = "+ext"
		}
		w("| %d | `OP_%s` | %s | %s | %s | %s |\n", o.num, o.name, code(o.operands), e, code(o.effect), cell(o.desc))
	}

	w("\n## Builtins\n\n")
	w("Called with `OP_BUILTIN`: `ra = builtin ext(rb .. rb+c-1)`, where `ext` is the id below. Arguments are\n")
	w("the registers `rb ..`; a builtin with two results writes `ra` and `ra+1`.\n\n")
	w("| Id | Name | Arguments | Results | Description |\n|---|---|---|---|---|\n")
	for _, o := range builtins {
		w("| %d | `B_%s` | %s | %s | %s |\n", o.num, o.name, code(o.args), code(o.results), cell(o.desc))
	}

	w("\n## Type ids and reserved types\n\n")
	w("`OP_TYPEIS` takes a `TY_*` id for basic types, or a struct type id. Struct types use their type-table\n")
	w("index: the reserved types below by their fixed index, an image's own types as `TYPE_OWN_BASE` (%s)\n", macro(opcodesH, "TYPE_OWN_BASE"))
	w("plus their position after the reserved rows (design.md §5.6, \"Types\"). Reserved types only grow at the\n")
	w("end, and only with `int` fields.\n\n")
	w("| Id | Name | Meaning |\n|---|---|---|\n")
	for _, d := range tys {
		w("| `%s` | `%s` | %s |\n", d.value, d.name, cell(d.comment))
	}
	w("\n| Index | Name | Fields |\n|---|---|---|\n")
	for _, d := range types {
		w("| %s | `%s` | %s |\n", d.value, d.name, cell(d.comment))
	}

	w("\n## Exit reasons\n\n")
	w("Codes 10..63 are kept for the VM; 64..99 are library failures (`R_FAILED` + a `GOGO_E_*` code); user\n")
	w("codes are >= 100.\n\n| Code | Name | Note |\n|---|---|---|\n")
	for _, d := range reasons {
		w("| %s | `R_%s` | %s |\n", d.value, d.name, cell(d.comment))
	}

	w("\n## Image file layout\n\n")
	w("Little-endian 32-bit words (`runtime/vm/image.h`; narrative in [design.md](design.md) §5.6). Images are\n")
	w("position-independent and run in place. Sections follow each other in this order:\n\n")
	w("| Section | Size (words) | Contents |\n|---|---|---|\n")
	w("| header | 8 | 0 magic `0x4F474F47` (\"GOGO\"); 1 version `major<<16 \\| minor`; 2 `n_funcs`; 3 `n_types`; 4 `consts_words`; 5 `code_words`; 6 `entry` (only validated: boot starts the `\"main\"` export); 7 `n_reserved` |\n")
	w("| functions | 3 x `n_funcs` | per function: 0 code offset (words, into the code section); 1 `nparams \\| nregs<<16`; 2 name (constant offset of a string) |\n")
	w("| types | 2 x `n_types` | per type: field count, name (constant offset); the first `n_reserved` rows are reserved types, then the image's own |\n")
	w("| constants | `consts_words` | strings, int64 boxes, byte blobs and other objects, each starting with a header word |\n")
	w("| code | `code_words` | instruction words and their `ext` words |\n")
	w("| constant map | ceil(`consts_words` / 32) | one bit per constant word, set where an object starts (word `i / 32`, bit `i %% 32`); read in place, no RAM |\n")
	w("| requirements | 1 + `n_requires` | the count, then one constant offset per name: a port driver (`\"kbd\"`, `\"tcp\"`) or a mount prefix starting with `/` |\n")
	w("| exports | 1 + 2 x `n_exports` | the count, then `{name constant offset, function index}` pairs; `main` is exported as `\"main\"` |\n\n")
	w("The loader checks the tables and the constant area (the map must mark exactly the object starts the\n")
	w("constant headers define; requirement and export names must be constant strings at marked starts;\n")
	w("function indexes in range) and refuses anything else (`IMG_ERR_BOUNDS`); a `major` other than the VM's,\n")
	w("or a `minor` above it, is `IMG_ERR_VERSION`. The compiler stamps each image with the lowest minor its\n")
	w("opcodes, builtins and reserved types need. Versioning policy and validation are in design.md §5.6.\n")
	return b.String(), nil
}

func main() {
	check := flag.Bool("check", false, "fail if docs/bytecode.md is not up to date")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	rd := func(p string) string {
		d, err := os.ReadFile(filepath.Join(*root, p))
		if err != nil {
			fmt.Fprintln(os.Stderr, "bcdoc:", err)
			os.Exit(2)
		}
		return string(d)
	}
	out, err := generate(rd("runtime/vm/opcodes.h"), rd("runtime/vm/image.h"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "bcdoc:", err)
		os.Exit(1)
	}
	dst := filepath.Join(*root, "docs/bytecode.md")
	if *check {
		cur, _ := os.ReadFile(dst)
		if string(cur) != out {
			fmt.Fprintln(os.Stderr, "bcdoc: docs/bytecode.md is stale: run `make bytecode-doc`")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(dst, []byte(out), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "bcdoc:", err)
		os.Exit(2)
	}
}
